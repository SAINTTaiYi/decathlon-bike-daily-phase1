#!/usr/bin/env node
import { execFileSync } from 'node:child_process'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { APP_VERSION, currentRelease } from '../apps/web/src/data/releaseNotes.js'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const packageJson = JSON.parse(await readFile(resolve(root, 'package.json'), 'utf8'))
const apiOutput = resolve(root, 'apps/api/src/generated/build-metadata.ts')
const workerOutput = resolve(root, 'apps/worker/src/generated/release-info.ts')

function git(args, fallback = '') {
  try {
    return execFileSync('git', args, { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim()
  } catch {
    return fallback
  }
}

const environmentSha = process.env.GITHUB_SHA?.trim() || process.env.COMMIT_SHA?.trim() || ''
const commitSha = environmentSha || git(['rev-parse', 'HEAD'], 'development')
const dirty = git(['status', '--porcelain'], '')
const gitSha = dirty && !environmentSha ? `${commitSha}-dirty` : commitSha
const generatedAt = new Date().toISOString()

await mkdir(dirname(apiOutput), { recursive: true })
await mkdir(dirname(workerOutput), { recursive: true })
await Promise.all([
  writeFile(apiOutput, [
    '// Generated by scripts/generate-build-metadata.mjs. Do not commit.',
    `export const BUILD_APP_VERSION = ${JSON.stringify(packageJson.version)}`,
    `export const BUILD_GIT_SHA = ${JSON.stringify(gitSha)}`,
    `export const BUILD_GENERATED_AT = ${JSON.stringify(generatedAt)}`,
    ''
  ].join('\n')),
  writeFile(workerOutput, [
    '// Generated by scripts/generate-build-metadata.mjs from apps/web/src/data/releaseNotes.js. Do not commit.',
    '// 发布公告的唯一事实源是 releaseNotes.js；本文件在 pretest/pretypecheck/prebuild 时自动重建。',
    'export const RELEASE_INFO = {',
    `  version: ${JSON.stringify(APP_VERSION)},`,
    `  date: ${JSON.stringify(currentRelease.date)},`,
    `  title: ${JSON.stringify(currentRelease.title)},`,
    `  summary: ${JSON.stringify(currentRelease.summary)},`,
    `  changes: ${JSON.stringify(currentRelease.changes)}`,
    '} as const',
    ''
  ].join('\n'))
])

console.log(JSON.stringify({ ok: true, appVersion: packageJson.version, gitSha, outputs: ['apps/api/src/generated/build-metadata.ts', 'apps/worker/src/generated/release-info.ts'] }))
